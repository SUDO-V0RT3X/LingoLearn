-- Placement question fixes (onboarding slice, 2xx range).
--
-- The placement test is a ladder: six levels of five questions, and it stops at the
-- first wrong answer. That only finds the right level when each band of five is
-- written for its level and the questions get harder in order. They did not:
--   * 202 seeded English q1-q5 with harder questions ("I have lived here ___ 2019",
--     a third conditional, a future perfect) and the app's own seed then kept them,
--     since it never overwrites a row. So an A1 learner met a B1 question first,
--     and q11 nearly repeated q1.
--   * Some fill-in questions accepted more than one right answer (q4, q9, q14, q18).
--   * Several isiZulu questions gave their answer away in the prompt or the
--     instruction (zq4, zq11, zq14, zq23, zq28, zq29), and zq6, zq17 and zq29 had
--     a wrongly formed answer.
--
-- This writes the canonical ladders (DEFAULT_QUESTIONS and DEFAULT_ZULU_QUESTIONS in
-- placementMethods.ts, which seed a fresh database) over whatever is stored, keyed by
-- id. Every id keeps its position (order_index = its number - 1), so no position is
-- ever claimed twice and an attempt in progress simply continues at its position.
-- The levels are the app's scale: 1=A1, 2=A1+, 3=A2, 4=B1, 5=B2, 6=C1.

